md("## 6. Experiment 1 — MAIN",
   "",
   "Within-domain-centred Pearson r over the 12 trained-on domains, `df = n - k - 1`. Every",
   "domain-level effect is removed, so what is left is specificity: which peptide *this* domain",
   "prefers.",
   "",
   "**A verdict of yes needs r < 0 at p < 0.025 *and* |r| above the same statistic for the average",
   "profile.** At df = 24 that means |r| >= 0.44; a weaker real signal returns a null, as stated in",
   "advance."),

code("def rmcorr(d, col, ycol='logKd'):",
     "    \"\"\"Pearson r on within-domain-centred values; df = n - k - 1.\"\"\"",
     "    # a domain measured once carries no within-domain information: centring sends it to 0,",
     "    # so it would spend a degree of freedom for nothing. Matters only to Exp 5a.",
     "    d = d[d.groupby('domain').domain.transform('size') >= 2]",
     "    g = d.groupby('domain')",
     "    x = (d[col] - g[col].transform('mean')).values",
     "    y = (d[ycol] - g[ycol].transform('mean')).values",
     "    n, k = len(d), d.domain.nunique()",
     "    df = n - k - 1",
     "    if df < 1 or np.std(x) < 1e-12: return dict(r=np.nan, p=np.nan, n=n, k=k, df=df)",
     "    r = float(np.corrcoef(x, y)[0, 1])",
     "    p = float(2 * tdist.sf(abs(r) * np.sqrt(df / max(1 - r * r, 1e-12)), df))",
     "    return dict(r=r, p=p, n=n, k=k, df=df)",
     "",
     "TR = D[D.group == 'trained']",
     "e1_model = rmcorr(TR, 'S_model'); e1_avg = rmcorr(TR, 'S_avg')",
     "e1_obs   = rmcorr(TR, 'S_obs')",
     "",
     "beats = abs(e1_model['r']) > abs(e1_avg['r'])",
     "E1_VERDICT = ('yes' if (e1_model['r'] < 0 and e1_model['p'] < ALPHA and beats) else 'no')",
     "for lab, v in [('model', e1_model), ('average profile', e1_avg), ('observed profile', e1_obs)]:",
     "    print(f'{lab:18s} r {v[\"r\"]:+.3f}  p {v[\"p\"]:.4g}  (n {v[\"n\"]}, k {v[\"k\"]}, df {v[\"df\"]})')",
     "print(f'\\nbeats the average profile: {beats}     MAIN VERDICT: {E1_VERDICT}')"),

md("## 7. Experiment 2 — the assumption-free version",
   "",
   "Per-domain Spearman for domains with at least 3 measurements, aggregated by a two-sided sign test",
   "on the direction. Declared in advance: with 8 domains this reaches 0.025 **only at 8/8**."),

code("def per_domain(d, col):",
     "    rows = []",
     "    for dom, g in d.groupby('domain'):",
     "        if len(g) < 3: continue",
     "        rho, p = spearmanr(g[col], g.logKd)",
     "        rows.append(dict(domain=dom, n=len(g), rho=float(rho), p=float(p)))",
     "    return pd.DataFrame(rows)",
     "",
     "def sign_test(t):",
     "    if not len(t): return dict(k=0, n=0, p=np.nan, median=np.nan, lo=np.nan, hi=np.nan)",
     "    k = int((t.rho < 0).sum())",
     "    bs = [np.median(np.random.default_rng(b).choice(t.rho.values, len(t))) for b in range(2000)]",
     "    lo, hi = np.percentile(bs, [2.5, 97.5])",
     "    return dict(k=k, n=len(t), p=float(binomtest(k, len(t), 0.5).pvalue),",
     "                median=float(t.rho.median()), lo=float(lo), hi=float(hi))",
     "",
     "PD_model, PD_obs = per_domain(TR, 'S_model'), per_domain(TR, 'S_obs')",
     "PD_model.to_csv(OUT / 'per_domain_E4.csv', index=False)",
     "s_model, s_obs = sign_test(PD_model), sign_test(PD_obs)",
     "print(PD_model.to_string(index=False))",
     "MIN_DOM = 8",
     "E2_VERDICT = ('too few' if s_model['n'] < MIN_DOM else",
     "              'yes' if (s_model['p'] < ALPHA and s_model['hi'] < 0) else 'no')",
     "for lab, s in [('model', s_model), ('observed', s_obs)]:",
     "    print(f'{lab:9s} {s[\"k\"]}/{s[\"n\"]} negative, sign test p {s[\"p\"]:.4g}, '",
     "          f'median rho {s[\"median\"]:+.3f} [{s[\"lo\"]:+.3f}, {s[\"hi\"]:+.3f}]')",
     "print(f'\\nEXP 2 VERDICT: {E2_VERDICT}')"),

