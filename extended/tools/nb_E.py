     "roc = roc.assign(wt_aa=mm[0], rpos=pd.to_numeric(mm[1], errors='coerce'), mut_aa=mm[2],",
     "                 rocklin_ddG=pd.to_numeric(roc[34], errors='coerce'))",
     "roc = roc.dropna(subset=['rpos','rocklin_ddG']).merge(ov, on='pdb_id')",
     "",
     "d = sh3.rename(columns={'domain_ID':'dom_ID'}).merge(",
