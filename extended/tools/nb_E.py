     "t = pd.DataFrame(ceil, columns=['gene','domain','n','ceiling','p','ours']).sort_values('ceiling', ascending=False)",
     "t['pct_of_ceiling'] = 100 * t.ours / t.ceiling",
     "t.to_csv(OUT / 'noise_ceiling_E2.csv', index=False)",
