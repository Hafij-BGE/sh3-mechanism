"""Generates the E-series notebooks (external validation of the frozen run).

    E2_domainome_external   validation against measured human abundance + the noise ceiling

E1, E3 and E4 will be added here as they are written; they share the setup and the
reporting helpers below.

Convention, carried over from the frozen run: each program writes a machine-written
RESULTS_<ID>.md and metrics_<ID>.json beside its tables. Nothing in RESULTS is typed
by hand. The hand-written interpretation lives in ANALYSIS_<ID>.md.
"""
import json, pathlib

def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": "\n".join(lines)}

def code(*lines):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": "\n".join(lines)}

