   "",
   "### Signs — the trap in this program",
   "",
   "| Quantity | Convention |",
   "|---|---|",
   "| `pred_ddG_fold` (ours) | **positive** = destabilising |",
   "| `normalized_fitness` (aPCA) | **negative** = destabilising |",
   "| Rocklin ΔΔG, column V35 | **negative** = destabilising |",
   "",
   "So ours correlates **negatively** with fitness, and the two assays correlate **positively** with",
