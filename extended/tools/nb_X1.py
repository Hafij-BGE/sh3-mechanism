     "    multi = t.str.contains(';', na=False)",
     "    out = pd.to_numeric(t.where(~multi), errors='coerce')",
     "    if multi.any():",
     "        wide = t[multi].str.split(';', expand=True).apply(pd.to_numeric, errors='coerce')",
