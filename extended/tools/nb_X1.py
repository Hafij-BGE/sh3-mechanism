     "#  - dbNSFP writes '.' for a missing value, not an empty field. Without na_values every",
     "#    predictor column looks 100% covered, which is how the first run reported it.",
     "#  - pandas infers dtypes PER CHUNK, so #chr is int64 in chunks that happen to hold only",
     "#    numeric chromosomes and object in the ones with X or Y. Concatenating those and",
     "#    writing parquet fails with ArrowInvalid. Reading everything as str makes the chunks",
     "#    agree; the numeric columns are converted once, after the concat.",
